// Builds a contraption through the UI and checks the mechanism and the audio it drives.
const { chromium } = require('/srv/rig/monad/node_modules/playwright-core');
const path = require('path');
const FILE = process.argv[2] || ('file://' + path.join(__dirname, 'cogs.html'));
const SHOT = process.env.COGS_SHOT || '';
(async () => {
  const b = await chromium.launch({ executablePath: (process.env.MONAD_CHROME || '/srv/rig/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome'),
    args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const p = await (await b.newContext({ viewport: { width: 1200, height: 800 } })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  let pass = true;
  const check = (label, ok, got) => { if (!ok) pass = false; console.log(('  ' + label).padEnd(58), JSON.stringify(got), ok ? '✓' : '✗'); };
  const probe = fn => p.evaluate(fn);
  const near = (a, b, tol) => Math.abs(a - b) <= tol;

  await p.goto(FILE); await p.waitForTimeout(400);
  await p.click('button[data-act=audio]');
  await p.waitForFunction(() => __cogs.engine().state === 'ready' && __cogs.engine().ac === 'running', null, { timeout: 5000 });
  const smooth = await probe(() => new Promise(r => { const s = []; const f = ts => { s.push([ts, __cogs.clock.view * 1000]); if (s.length < 40) requestAnimationFrame(f); else {
    const k = s.slice(1).map(([t, v], i) => (v - s[i][1]) / (t - s[i][0])).filter(Number.isFinite); r(Math.max(...k.map(x => Math.abs(x - 1)))); } }; requestAnimationFrame(f); }));
  check('drawn motion advances with the frame clock (worst frame within 5%)', smooth < .05, +smooth.toFixed(4));
  await p.click('button[data-act=clear]');
  const rect = await probe(() => { const r = document.querySelector('#c').getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 }; });
  const at = (x, y) => [rect.x + x, rect.y + y];
  const tool = t => p.click(`button[data-tool=${t}]`);
  const drag = async (a, z) => { await p.mouse.move(...at(...a)); await p.mouse.down(); await p.mouse.move(...at(...z), { steps: 6 }); await p.mouse.up(); };
  const tap = async a => { await p.mouse.move(...at(...a)); await p.mouse.down(); await p.mouse.up(); };
  const field = (k, v) => p.fill(`#panel fieldset:nth-of-type(4) [data-k="${k}"] input[type=number]`, String(v));

  console.log('GEARS');
  await tool('cog'); await drag([0, 0], [46, 0]); await field('motor rpm', 60);
  await tool('cog'); await drag([70, 0], [93, 0]);
  const gears = await probe(() => __cogs.W.cogs.map(c => ({ n: c.n, x: c.x, rpm: c.w * 60 / (2 * Math.PI), jam: c.jam })));
  check('drawn teeth 24 and 12', gears[0].n === 24 && gears[1].n === 12, gears.map(g => g.n));
  check('second cog snapped to pitch distance 68.75', near(gears[1].x, 36 * 12 / (2 * Math.PI), 1e-9), gears[1].x);
  check('60 rpm drives -120 rpm', near(gears[0].rpm, 60, 1e-9) && near(gears[1].rpm, -120, 1e-9), gears.map(g => g.rpm));

  console.log('ARMS AND PADS');
  await tool('arm'); await drag([0, 0], [0, -80]);
  await tool('arm'); await drag([68.75, 0], [68.75, 40]);
  await tool('pad'); await tap([-60, -30]);
  await tool('pad'); await tap([98.75, 20]);
  await p.click('button[data-act="reset hits"]'); await p.waitForTimeout(4000);
  const hits = await probe(() => {
    const [a, b] = __cogs.W.pads, log = __cogs.stats.log;
    const times = id => log.filter(l => l.src.endsWith('>pad' + id)).map(l => l.t);
    const gaps = ts => ts.slice(1).map((t, i) => t - ts[i]);
    return { a: a.hits, b: b.hits, gapsA: gaps(times(a.id)), gapsB: gaps(times(b.id)), vA: a.lastV, late: __cogs.stats.late };
  });
  check('60 rpm arm: 4 hits in 4 s', hits.a >= 3 && hits.a <= 5, hits.a);
  check('-120 rpm arm: 8 hits in 4 s', hits.b >= 7 && hits.b <= 9, hits.b);
  check('hit period 1 s to 1e-6', hits.gapsA.length > 1 && hits.gapsA.every(g => near(g, 1, 1e-6)), hits.gapsA);
  check('hit period 0.5 s to 1e-6', hits.gapsB.length > 1 && hits.gapsB.every(g => near(g, .5, 1e-6)), hits.gapsB);
  const vTangent = 2 * Math.PI * Math.sqrt(60 * 60 + 30 * 30 - 144);
  check('impact speed = w * tangent radius', near(hits.vA, vTangent, 1e-6), [hits.vA, vTangent]);
  check('no event scheduled late', hits.late === 0, hits.late);

  console.log('JAM');
  const selectCog = async pts => { for (const pt of pts) { await tap(pt); if (await probe(() => document.querySelector('#panel fieldset:nth-of-type(4) legend').textContent.startsWith('cog'))) return; } throw new Error('no cog selected'); };
  await tool('select'); await selectCog([[68.75, 15], [55, -10], [80, -12], [62, 18]]); await field('motor rpm', 100);
  const jam = await probe(() => __cogs.W.cogs.map(c => [c.jam, c.w]));
  check('two disagreeing motors jam the train', jam.every(([j, w]) => j && w === 0), jam);
  await field('motor rpm', -120);
  const ok = await probe(() => __cogs.W.cogs.map(c => [c.jam, c.w * 60 / (2 * Math.PI)]));
  check('agreeing motors turn', ok.every(([j]) => !j) && near(ok[1][1], -120, 1e-9), ok);
  await field('motor rpm', 0);

  console.log('DISC AND READER');
  await tool('disc'); await tap([0, 170]);
  await tool('dot'); for (const pt of [[40, 170], [0, 240], [-80, 170]]) await tap(pt);
  await tool('reader'); await drag([0, 165], [0, 80]);
  await tool('select'); await selectCog([[80, 175], [-70, 190]]); await field('motor rpm', 30);
  const disc = await probe(() => { const c = __cogs.W.cogs[2]; return { n: c.n, dots: c.track.dots.length, rpm: c.w * 60 / (2 * Math.PI), strikes: __cogs.engine().strikes }; });
  check('disc: 48 teeth, 3 dots, 30 rpm', disc.n === 48 && disc.dots === 3 && near(disc.rpm, 30, 1e-9), disc);
  await p.click('button[data-act="reset hits"]'); await p.waitForTimeout(4200);
  const rd = await probe(() => ({ hits: __cogs.W.readers[0].hits, rings: [...new Set(__cogs.stats.log.filter(l => l.src.includes('>reader')).map(l => l.src.split('>')[0]))], eng: __cogs.engine() }));
  check('reader: 3 dots x 2 revolutions', rd.hits >= 5 && rd.hits <= 7, rd.hits);
  check('three distinct rings sounded', rd.rings.length === 3, rd.rings);
  check('engine consumed the modal strikes', rd.eng.strikes - disc.strikes >= rd.hits - 1 && rd.eng.drops === 0, { strikes: rd.eng.strikes - disc.strikes, drops: rd.eng.drops });
  const peak = await probe(() => document.querySelector('#panel [data-k="peak dB"] b').textContent);
  check('output reaches the destination', parseFloat(peak) > -60, peak);

  console.log('ROLL');
  const box = await p.evaluate(() => { const cv = document.querySelector('#panel fieldset:nth-of-type(4) canvas'); cv.scrollIntoView({ block: 'center' }); const r = cv.getBoundingClientRect(); return { x: r.left, y: r.top, w: r.width, h: r.height }; });
  const rows = Math.round(box.h / 11), cw = (box.w - 30) / 16, cell = (col, row) => [box.x + 30 + (col + .5) * cw, box.y + (row + .5) * 11];
  const dots = () => probe(() => __cogs.W.cogs[2].track.dots.map(d => [d.ring, +d.a.toFixed(6)]));
  const n0 = (await dots()).length;
  await p.mouse.click(...cell(2, rows - 1));
  const added = (await dots()).slice(-1)[0];
  check('roll cell col 2, bottom row -> ring 0 at -2 steps', (await dots()).length === n0 + 1 && added[0] === 0 && near(added[1], 2 * Math.PI - 2 * Math.PI / 16 * 2, 1e-6), added);
  await p.mouse.click(...cell(2, rows - 1));
  check('second click removes it', (await dots()).length === n0, (await dots()).length - n0);
  await p.mouse.move(...cell(0, rows - 6)); await p.mouse.down();
  for (let c = 1; c < 4; c++) await p.mouse.move(...cell(c, rows - 6), { steps: 3 });
  await p.mouse.up();
  const painted = (await dots()).filter(d => d[0] === 5);
  check('drag paints 4 cells on ring 5', painted.length === 4, painted);
  await p.click('button[data-act="reset hits"]'); await p.waitForTimeout(2100);
  const r5 = await probe(() => __cogs.stats.log.filter(l => l.src.endsWith('.ring5>reader' + __cogs.W.readers[0].id)).length);
  check('painted ring 5: 4 dots in one 2 s revolution (+1 at the window edge)', r5 === 4 || r5 === 5, r5);

  console.log('PAUSE AND PERSIST');
  await p.click('button[data-act=pause]'); const before = await probe(() => __cogs.stats.events);
  await p.waitForTimeout(1000); const after = await probe(() => __cogs.stats.events);
  check('paused: no events', after - before <= 1, after - before);
  await p.click('button[data-act=pause]');
  await p.waitForTimeout(600); await p.reload(); await p.waitForTimeout(400);
  const world = await probe(() => __cogs.W.cogs.length + ' ' + __cogs.W.arms.length + ' ' + __cogs.W.pads.length + ' ' + __cogs.W.readers.length);
  check('world restored after reload', world === '3 2 2 1', world);
  console.log('PINCH');
  const tp = await (await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })).newPage();
  await tp.goto(FILE); await tp.waitForTimeout(400);
  await tp.click('button[data-tool=pad]');
  const c0 = await tp.evaluate(() => { const r = document.querySelector('#c').getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2, zoom: __cogs.S.zoom, pads: __cogs.W.pads.length, view: { ...__cogs.serialize().view } }; });
  const cdp = await tp.context().newCDPSession(tp);
  const touch = (type, pts) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: pts.map(([x, y], id) => ({ x, y, id })) });
  await touch('touchStart', [[c0.x - 50, c0.y]]);
  await touch('touchStart', [[c0.x - 50, c0.y], [c0.x + 50, c0.y]]);
  for (let k = 1; k <= 10; k++) await touch('touchMove', [[c0.x - 50 - 5 * k, c0.y], [c0.x + 50 + 5 * k, c0.y]]);
  await touch('touchEnd', []); await tp.waitForTimeout(200);
  const c1 = await tp.evaluate(() => ({ zoom: __cogs.S.zoom, pads: __cogs.W.pads.length, view: { ...__cogs.serialize().view } }));
  check('pinch 100 -> 200 px doubles zoom', near(c1.zoom / c0.zoom, 2, .02), [c0.zoom, c1.zoom]);
  check('world under the fingers stays put', near(c1.view.x, c0.view.x, .5) && near(c1.view.y, c0.view.y, .5), [c0.view, c1.view]);
  check('pinch with pad tool creates no pad', c1.pads === c0.pads, [c0.pads, c1.pads]);

  console.log('BELTS, TEMPO, STRINGS, COMB, PROBABILITY, EUCLID, SHARE');
  await p.click('button[data-act=clear]');
  const setting = (k, v) => p.fill(`#panel fieldset:nth-of-type(5) [data-k="${k}"] input[type=number]`, String(v));
  const pick = (k, v) => p.selectOption(`#panel fieldset:nth-of-type(4) [data-k="${k}"] select`, v);
  const rpm = () => probe(() => __cogs.W.cogs.map(c => +(c.w * 60 / (2 * Math.PI)).toFixed(6)));
  await tool('cog'); await drag([-100, 0], [-54, 0]); await field('motor rpm', 60);
  await tool('cog'); await drag([100, 0], [123, 0]);
  await tool('belt'); await drag([-100, 0], [100, 0]);
  check('open belt: same direction, ratio 24/12', JSON.stringify(await rpm()) === '[60,120]', await rpm());
  await field('crossed', 1);
  check('crossed belt reverses', JSON.stringify(await rpm()) === '[60,-120]', await rpm());
  await setting('bpm lock', 240); await tool('select'); await selectCog([[-100, 25], [-120, -10], [-80, 20]]); await pick('revs/bar', '1/2');
  check('240 bpm, 4/4, 1/2 rev per bar = 30 rpm', JSON.stringify(await rpm()) === '[30,-60]', await rpm());
  await tool('arm'); await drag([-100, 0], [-100, -60]);
  await tool('string'); await drag([-180, -40], [-20, -40]); await p.waitForTimeout(300);
  const note = await probe(() => document.querySelector('#panel fieldset:nth-of-type(4) [data-k="note"] b').textContent);
  check('160 px string at 220 Hz/200 px quantizes to C#4', note.startsWith('C#4 61'), note);
  const sk0 = (await probe(() => __cogs.engine())).strikes || 0;
  await p.click('button[data-act="reset hits"]'); await p.waitForTimeout(2300);
  const st = await probe(() => { const s = __cogs.W.strings[0]; return { hits: s.hits, u: s.lastU }; });
  const uOk = [.5 - Math.sqrt(60 * 60 - 40 * 40) / 160, .5 + Math.sqrt(60 * 60 - 40 * 40) / 160].some(u => near(st.u, u, 1e-3));
  check('tip crosses the string twice per revolution', st.hits >= 2 && st.hits <= 3, st.hits);
  check('pluck point is where the tip circle cuts the string', uOk, st.u);
  await p.waitForTimeout(300);
  check('plucks reach the engine', ((await probe(() => __cogs.engine())).strikes || 0) > sk0, sk0);
  await tool('disc'); await tap([0, 150]); await pick('revs/bar', '1');
  await p.fill('#panel fieldset:nth-of-type(4) [data-k="euclid ring"] input[type=number]', '2');
  await p.fill('#panel fieldset:nth-of-type(4) [data-k="euclid k"] input[type=number]', '3');
  await p.click('text=euclid fill');
  const eu = await probe(() => __cogs.W.cogs[2].track.dots.map(d => d.ring));
  check('euclid 3 in 16 on ring 2', eu.length === 3 && eu.every(r => r === 2), eu);
  await tool('reader'); await drag([0, 145], [0, 60]);
  await field('comb tines', 4);
  await p.click('button[data-act="reset hits"]'); await p.waitForTimeout(2050);
  const rdr = await probe(() => ({ hits: __cogs.W.readers[0].hits, midi: __cogs.W.readers[0].lastMidi }));
  check('reader: 3 dots x 2 revolutions', rdr.hits >= 5 && rdr.hits <= 7, rdr.hits);
  check('comb: ring 2 crosses tine 1 of 4 -> D4 (62)', rdr.midi === 62, rdr.midi);
  await tool('select'); await selectCog([[60, 150], [-60, 160]]);
  await p.fill('#panel fieldset:nth-of-type(4) [data-k="brush p"] input[type=number]', '0'); await p.click('text=euclid fill');
  await p.click('button[data-act="reset hits"]'); await p.waitForTimeout(1500);
  const silent = await probe(() => __cogs.W.readers[0].hits);
  check('probability 0: silent', silent === 0, silent);
  await p.fill('#panel fieldset:nth-of-type(4) [data-k="brush p"] input[type=number]', '0.5'); await p.click('text=euclid fill');
  await p.click('button[data-act="reset hits"]'); await p.waitForTimeout(4050);
  const half = await probe(() => __cogs.W.readers[0].hits);
  check('probability 0.5: some of 12 play', half > 0 && half < 12, half);
  await p.click('text=share'); await p.waitForFunction(() => document.querySelector('#panel textarea').value.includes('#w='));
  const url = await p.inputValue('#panel textarea');
  check('share yields a #w= url', /#w=[\w-]+$/.test(url), url.slice(0, 50) + '…');
  const sp = await (await b.newContext({ viewport: { width: 1200, height: 800 } })).newPage();
  await sp.goto(url); await sp.waitForTimeout(600);
  const counts = o => [o.cogs.length, o.arms.length, o.belts.length, o.strings.length, o.readers.length, o.cogs[2].track.dots.length];
  const here = counts(await probe(() => __cogs.serialize())), there = counts(await sp.evaluate(() => __cogs.serialize()));
  check('shared url rebuilds the same world', JSON.stringify(here) === JSON.stringify(there), [here, there]);

  if (SHOT) await p.screenshot({ path: SHOT });
  check('page errors', errs.length === 0, errs.slice(0, 3));
  console.log(pass ? '\nCOGS: PASS' : '\nCOGS: FAIL');
  await b.close(); process.exit(pass ? 0 : 1);
})();
